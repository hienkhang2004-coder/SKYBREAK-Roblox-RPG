function ArsenalExpansionConfig.GetActiveArmorSetInfo(equippedTable)
    local eq = type(equippedTable) == "table" and equippedTable or {}
    local equippedBySlot = {
        Helm = tostring(eq.Helm or eq.Helmet or ""),
        Chest = tostring(eq.Chest or eq.Armor or ""),
        Gauntlets = tostring(eq.Gauntlets or eq.Gloves or ""),
        Greaves = tostring(eq.Greaves or eq.Boots or ""),
    }

    local countsById = {}
    local activeSets = {}
    local totalBonusStats = { HP = 0, DEF = 0, ATK = 0, CRIT = 0, SPEED = 0 }
    local bestSet = nil
    local bestCount = 0

    for _, setDef in ipairs(ArsenalExpansionConfig.ArmorSets) do
        local count = 0
        local matchedSlots = {}
        for slotKey, expectedId in pairs(setDef.Pieces) do
            local curId = equippedBySlot[slotKey]
            local isMatch = (curId ~= "" and curId == expectedId)
            if not isMatch and setDef.Aliases and setDef.Aliases[slotKey] and setDef.Aliases[slotKey][curId] then
                isMatch = true
            end
            if isMatch then
                count = count + 1
                matchedSlots[slotKey] = curId
            end
        end

        countsById[setDef.Id] = count
        if count > 0 then
            local b2 = count >= 2
            local b4 = count >= 4
            if b2 and setDef.Stats2 then
                for k, v in pairs(setDef.Stats2) do
                    totalBonusStats[k] = (totalBonusStats[k] or 0) + v
                end
            end
            if b4 and setDef.Stats4 then
                for k, v in pairs(setDef.Stats4) do
                    totalBonusStats[k] = (totalBonusStats[k] or 0) + v
                end
            end

            local entry = {
                Id = setDef.Id,
                Set = setDef,
                NameVi = setDef.NameVi,
                NameEn = setDef.NameEn,
                AccentHex = setDef.AccentHex,
                Pieces = setDef.Pieces,
                Count = count,
                EquippedCount = count,
                MaxPieces = 4,
                MatchedSlots = matchedSlots,
                Bonus2Vi = setDef.Bonus2Vi,
                Bonus2En = setDef.Bonus2En,
                Bonus4Vi = setDef.Bonus4Vi,
                Bonus4En = setDef.Bonus4En,
                Bonus2Active = b2,
                Bonus4Active = b4,
            }
            table.insert(activeSets, entry)

            if count > bestCount or (count == bestCount and bestSet and setDef.LevelReq > (bestSet.Set.LevelReq or 0)) then
                bestCount = count
                bestSet = entry
            end
        end
    end

    table.sort(activeSets, function(a, b)
        if a.Count ~= b.Count then
            return a.Count > b.Count
        end
        return (a.Set.LevelReq or 0) > (b.Set.LevelReq or 0)
    end)

    return {
        BestSet = bestSet,
        ActiveSet = bestSet,
        BestSetId = bestSet and bestSet.Id or nil,
        Count = bestCount,
        EquippedCount = bestCount,
        MaxPieces = 4,
        Bonus2Active = bestCount >= 2,
        Bonus4Active = bestCount >= 4,
        ActiveSets = activeSets,
        SetCounts = countsById,
        BonusStats = totalBonusStats,
    }
end

